        public static string[] Mirror(string[] rows)
        {
            var mirrored = new string[rows.Length];
            for (int i = 0; i < rows.Length; i++)
            {
                char[] chars = rows[i].ToCharArray();
                Array.Reverse(chars);
                mirrored[i] = new string(chars);
            }
            return mirrored;
        }

        static LayoutDef Def(string name, int levels, int minWorld, params string[] rows) =>
            new LayoutDef { name = name, levels = levels, minWorld = minWorld, rows = rows };
