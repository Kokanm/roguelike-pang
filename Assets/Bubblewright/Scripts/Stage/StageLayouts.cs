        public static string[] Mirror(string[] rows)
        {
            var mirrored = new string[rows.Length];
            for (int i = 0; i < rows.Length; i++)
            {
                char[] chars = rows[i].ToCharArray();
                Array.Reverse(chars);
                mirrored[i] = new string(chars);
            }
            return mirrored;
        }

        static LayoutDef Def(string name, int levels, int minWorld, params string[] rows) =>
            new LayoutDef { name = name, levels = levels, minWorld = minWorld, rows = rows };

        static LayoutDef GapDef(string name, int levels, params string[] rows) =>
            new LayoutDef { name = name, levels = levels, minWorld = 2, rows = rows };

        static LayoutDef CatacombDef(string name, int levels, bool needsBreaking, params string[] rows) =>
            new LayoutDef
            {
                name = name,
                levels = levels,
                minWorld = 5,
                onlyWorld = 5,
                needsBreaking = needsBreaking,
                rows = rows,
            };

        static LayoutDef SealedCatacombDef(string name, int levels, params string[] rows)
        {
            LayoutDef layout = CatacombDef(name, levels, true, rows);
            layout.bubbleMinY = 10f;
            return layout;
        }
